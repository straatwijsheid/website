#!/usr/bin/env python3
"""Generate tokens.css from tokens.json and check WCAG contrast.

    python3 branding/build_tokens.py

Fails (exit 1) if a text/background pair that is used for text drops below
4.5:1 (AA, normal text). Map fill colours are not text and are not checked.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).parent
T = json.loads((HERE / "tokens.json").read_text())


def lum(hex_):
    h = hex_.lstrip("#")
    rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def checks():
    c = T["color"]
    for mode in ("light", "dark"):
        m = c[mode]
        for fg, bgs in (("ink", ("paper", "surface")), ("ink-muted", ("paper", "surface")),
                        ("link", ("paper", "surface")), ("brand-ink", ("brand",)), ("accent-ink", ("accent",)),
                        ("accent-text", ("paper", "surface"))):
            for bg in bgs:
                yield f"{mode}: {fg} on {bg}", m[fg], m[bg]
        for cat, v in c["category"].items():
            fg = v["text"] if mode == "light" else v["dark"]["text"]
            for bgname, bg in (("paper", m["paper"]),
                               ("tint", v["tint"] if mode == "light" else v["dark"]["tint"])):
                yield f"{mode}: {cat} text on {bgname}", fg, bg


def write_fonts():
    """fonts.css: @font-face for the self-hosted Overpass files."""
    names = {400: "regular", 600: "semibold", 700: "bold", 800: "extrabold"}
    blocks = []
    for w in T["font"]["weights"].values():
        blocks.append("@font-face {\n  font-family: 'Overpass';\n"
                      f"  src: url('fonts/overpass-{names[w]}.woff2') format('woff2');\n"
                      f"  font-weight: {w};\n  font-style: normal;\n  font-display: swap;\n}}\n")
    (HERE / "fonts.css").write_text("/* Generated by build_tokens.py. Do not edit. */\n" + "\n".join(blocks))
    print("wrote fonts.css")


def write_preview():
    """preview.html: tokens.css and the logos inlined, so it renders anywhere."""
    import base64
    s = (HERE / "preview.template.html").read_text()
    import base64 as b64
    fonts = (HERE / "fonts.css").read_text()
    fonts = re.sub(r"url\('(fonts/[^']+)'\)",
                   lambda m: "url('data:font/woff2;base64," + b64.b64encode((HERE / m.group(1)).read_bytes()).decode() + "')", fonts)
    s = s.replace("/*TOKENS*/", fonts + (HERE / "tokens.css").read_text())

    def inline(m):
        data = (HERE / m.group(1)).read_bytes()
        return 'src="data:image/svg+xml;base64,' + base64.b64encode(data).decode() + '"'

    s = re.sub(r'src="(logo/[^"]+\.svg)"', inline, s)
    (HERE / "preview.html").write_text(s)
    print("wrote preview.html")


def main():
    bad = 0
    for name, fg, bg in checks():
        r = ratio(fg, bg)
        flag = "ok " if r >= 4.5 else "LOW"
        bad += r < 4.5
        print(f"{flag} {r:5.2f}  {name}  ({fg} on {bg})")

    c = T["color"]
    out = ["/* Generated by build_tokens.py from tokens.json. Do not edit. */", ":root {"]

    def light_vars():
        for k, v in c["light"].items():
            yield f"--sw-{k}", v
        for cat, v in c["category"].items():
            for k in ("base", "tint", "text"):
                yield f"--sw-{cat}-{k}", v[k]
        for cat, rows in c["subgroup"].items():
            for sid, _label, col in rows:
                yield f"--sw-{cat}-{sid}", col
        for n, col in c["tier"].items():
            yield f"--sw-tier-{n}", col

    def dark_vars():
        for k, v in c["dark"].items():
            yield f"--sw-{k}", v
        for cat, v in c["category"].items():
            yield f"--sw-{cat}-tint", v["dark"]["tint"]
            yield f"--sw-{cat}-text", v["dark"]["text"]

    out += [f"  {k}: {v};" for k, v in light_vars()]
    out += [f"  --sw-font-{k}: {v};" for k, v in T["font"].items() if k != "weights"]
    out += [f"  --sw-radius-{k}: {v};" for k, v in T["radius"].items()]
    out += [f"  --sw-space-{k}: {v};" for k, v in T["space"].items()]
    out += ["  color-scheme: light dark;", "}"]
    dark = list(dark_vars())
    out += ["@media (prefers-color-scheme: dark) {",
            "  :root:not([data-theme=\"light\"]) {"]
    out += [f"    {k}: {v};" for k, v in dark]
    out += ["  }", "}", ":root[data-theme=\"dark\"] {"]
    out += [f"  {k}: {v};" for k, v in dark]
    out += ["}"]
    (HERE / "tokens.css").write_text("\n".join(out) + "\n")
    print("wrote tokens.css")
    write_fonts()
    write_preview()
    return 1 if bad else 0


sys.exit(main())
